import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
test('English cleaner workspace preserves applicant identity without bypassing approval',async({page,request},testInfo)=>{
  const password='Cleaner-system-test-123!',email=`ui-cleaner-${randomUUID()}@example.test`;
  const result=await request.post('http://127.0.0.1:15238/api/auth/register',{data:{fullName:'Đăng nhập',email,password,role:'Cleaner',city:'Test city'}});expect(result.status()).toBe(200);
  const originalBio=(await result.json()).user.cleanerProfile.bio;
  await page.goto('/');await page.getByLabel('Language / Ngôn ngữ').selectOption('en');await page.getByLabel('Appearance / Giao diện').selectOption('dark');await page.getByLabel('Email',{exact:true}).fill(email);await page.getByLabel('Password',{exact:true}).fill(password);await page.getByRole('button',{name:'Sign in',exact:true}).click();
  await expect(page.locator('.account strong')).toHaveText('Đăng nhập');await expect(page.getByRole('link',{name:'Find work',exact:true})).toHaveCount(0);await expect(page.getByRole('heading',{name:'Apply and get approved',exact:true})).toBeVisible();
  await expect(page.getByRole('button',{name:'Pending review',exact:true})).toBeDisabled();
  await expect(page.getByLabel('About',{exact:true})).toHaveValue(originalBio);
  await page.screenshot({path:testInfo.outputPath('english-dark-cleaner.png'),fullPage:true});
  await page.reload();await expect(page.locator('.account strong')).toHaveText('Đăng nhập');await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
});
test('language and theme update without rebuilding forms and persist after reload',async({page})=>{
  await page.goto('/');
  await page.getByLabel('Email',{exact:true}).fill('language@example.test');
  await page.getByLabel('Mật khẩu',{exact:true}).fill('Typed-secret-123!');
  await page.getByLabel('Language / Ngôn ngữ').selectOption('en');
  await expect(page.getByRole('heading',{name:'Sign in',exact:true})).toBeVisible();
  await expect(page.getByLabel('Email',{exact:true})).toHaveValue('language@example.test');
  await expect(page.getByLabel('Password',{exact:true})).toHaveValue('Typed-secret-123!');
  await page.getByLabel('Appearance / Giao diện').selectOption('dark');
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  await expect(page.getByLabel('Email',{exact:true})).toHaveCSS('background-color','rgb(25, 42, 37)');
  await page.getByRole('button',{name:'Forgot password?',exact:true}).click();
  await page.getByLabel('Recovery email',{exact:true}).fill('kept@example.test');
  await page.getByLabel('Language / Ngôn ngữ').selectOption('vi');
  await expect(page.getByLabel('Email khôi phục',{exact:true})).toHaveValue('kept@example.test');
  await page.getByLabel('Language / Ngôn ngữ').selectOption('en');
  await page.reload();
  await expect(page.getByRole('heading',{name:'Sign in',exact:true})).toBeVisible();
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  await page.emulateMedia({colorScheme:'light'});
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
  await page.getByLabel('Appearance / Giao diện').selectOption('system');
  await expect(page.locator('html')).toHaveAttribute('data-theme','light');
  await page.emulateMedia({colorScheme:'dark'});
  await expect(page.locator('html')).toHaveAttribute('data-theme','dark');
});
